public class For_loops {
    public static void main(String[] args) {
        //for loops 
         for (int i=0;i<10;i++)
        {
            System.out.println("hello bro!!!");

        }
        

        for(int i=1;i<=10;i++)
        {
            System.out.println("hello bro!!!");

        }
            

        for(int i=0;i<10;i++)
        {
            System.out.println(i);

        }
            

        for(int i=1;i<=10;i++)
        {
            System.out.println(i);
        }

    }
    
}
